// Generate the SQL Editor scheduler from the canonical migration. No live service access.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const SLUG_JOB_NAME = 'book-doctor-public-book-slugs-20261027';
export const SLUG_JOB_MARKER = 'book-doctor:public-book-slugs:20261027000000';
const quote = (value) => `'${value.replaceAll("'", "''")}'`;

export function prepareSlugBackground(source) {
	if (!/^begin;\r?$/m.test(source) || !/^commit;\s*$/m.test(source))
		throw new Error('Expected one canonical migration transaction');
	const hash = createHash('sha256').update(source).digest('hex');
	const migration = source
		.replace(/^begin;\r?\n/m, '')
		.replace(/^commit;\s*$/m, '')
		.replace("statement_timeout = '120s'", "statement_timeout = '5min'")
		.trim();
	const command = `-- ${SLUG_JOB_MARKER}
set statement_timeout = '5min';
set lock_timeout = '2s';
do $slug_worker$
declare
  v_started timestamptz := clock_timestamp();
  v_error_state text;
  v_error_message text;
  v_books bigint;
begin
  begin
    if not pg_catalog.pg_try_advisory_xact_lock(20261027, 2)
      or not pg_catalog.pg_try_advisory_xact_lock(20261027, 1) then
      raise exception 'Another slug migration/allocator is running';
    end if;
    -- All DDL and backfill run in this exception subtransaction, without inner COMMIT.
    execute ${quote(migration)};
    select count(*) into v_books from public.books;
  exception
    when query_canceled then v_error_state := sqlstate; v_error_message := sqlerrm;
    when others then v_error_state := sqlstate; v_error_message := sqlerrm;
  end;
  update private.book_slug_installation set
    state = case when v_error_state is null then 'completed' else 'failed' end,
    started_at = v_started, finished_at = clock_timestamp(), book_count = v_books,
    error_sqlstate = v_error_state, error_message = left(v_error_message,1000)
  where migration_key = '20261027000000_public_book_slugs' and migration_sha256 = '${hash}';
  -- Removal commits AFTER the attempt, so Cron cannot cancel its own running migration.
  perform cron.unschedule(${quote(SLUG_JOB_NAME)});
end;
$slug_worker$;
`;
	return `-- GENERATED by scripts/prepare-book-slug-background.mjs from the canonical migration.
-- Run this ENTIRE file in Supabase SQL Editor: Database / postgres.
-- Use INSTEAD OF rerunning 20261027000000_public_book_slugs.sql in the foreground.
-- Requires the existing pg_cron extension; no extensions or global settings are changed.
-- Original migration SHA-256: ${hash}
-- The short request schedules work; the job normally starts at the next minute.
-- The migration runs atomically with a five-minute SQL limit and two-second lock limit.
-- The original backfill still updates every catalog row and holds its schema lock until commit.
-- On SQL failure/timeout, migration changes roll back; the private attempt records failure.
-- The job removes itself after the attempt. Cron success alone is not migration success.
-- Server/connection loss before cleanup commits can leave a job registered.
-- Check book-slug-background-status.sql before ANY retry; never run both install paths.
begin;
set local statement_timeout = '20s';
set local lock_timeout = '2s';
create schema if not exists private;
create table if not exists private.book_slug_installation (
  migration_key text primary key, migration_sha256 text not null, attempt integer not null,
  state text not null check(state in ('queued','completed','failed')),
  queued_at timestamptz not null, started_at timestamptz, finished_at timestamptz,
  book_count bigint, error_sqlstate text, error_message text
);
alter table private.book_slug_installation enable row level security;
revoke all on private.book_slug_installation from public, anon, authenticated, service_role;
do $schedule_slug$
begin
  if current_user <> 'postgres' then raise exception 'Run as postgres'; end if;
  if not exists (select 1 from pg_catalog.pg_extension where extname = 'pg_cron') then
    raise exception 'pg_cron is not installed; no job was scheduled';
  end if;
  if not pg_catalog.pg_try_advisory_xact_lock(20261027, 2)
    or not pg_catalog.pg_try_advisory_xact_lock(20261027, 1) then
    raise exception 'A slug migration/allocator is already running; inspect status';
  end if;
  if exists (select 1 from pg_catalog.pg_attribute where attrelid = 'public.books'::regclass
    and attname = 'slug' and attnum > 0 and not attisdropped) then
    raise exception 'books.slug already exists; inspect installation status instead of rescheduling';
  end if;
  if exists (select 1 from pg_catalog.pg_locks where locktype = 'relation'
    and relation = 'public.books'::regclass and mode = 'AccessExclusiveLock'
    and pid <> pg_backend_pid()) then
    raise exception 'Another catalog schema transaction is open; inspect status';
  end if;
  if exists (select 1 from pg_catalog.pg_stat_activity where datname = current_database()
    and pid <> pg_backend_pid() and state in ('active', 'idle in transaction')
    and position(${quote(SLUG_JOB_MARKER)} in coalesce(query, '')) > 0) then
    raise exception 'A background slug session is already open; inspect status';
  end if;
  if exists (select 1 from cron.job where jobname = ${quote(SLUG_JOB_NAME)}) then
    raise exception 'Slug migration job is already scheduled; inspect status';
  end if;
  insert into private.book_slug_installation(migration_key,migration_sha256,attempt,state,queued_at)
  values('20261027000000_public_book_slugs','${hash}',1,'queued',clock_timestamp())
  on conflict(migration_key) do update set migration_sha256=excluded.migration_sha256,
    attempt=private.book_slug_installation.attempt+1,state='queued',queued_at=excluded.queued_at,
    started_at=null,finished_at=null,book_count=null,error_sqlstate=null,error_message=null;
  perform cron.schedule(${quote(SLUG_JOB_NAME)}, '* * * * *', ${quote(command)});
end;
$schedule_slug$;
commit;
select jsonb_build_object(
  'migration', '20261027000000_public_book_slugs.sql',
  'scheduled_job', (select jsonb_build_object('job_id', jobid, 'active', active,
    'schedule', schedule, 'database', database, 'role', username)
    from cron.job where jobname = ${quote(SLUG_JOB_NAME)}),
  'next_step', 'Run book-slug-background-status.sql after the next minute; continue only once all four slug flags are true, recorded_attempt.state is completed, and the job/session have finished.'
) as book_slug_background_schedule;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	const source = readFileSync(
		new URL('../supabase/migrations/20261027000000_public_book_slugs.sql', import.meta.url),
		'utf8'
	);
	writeFileSync(
		new URL('catalog/apply-book-slugs-background.sql', import.meta.url),
		prepareSlugBackground(source)
	);
	console.log('Prepared apply-book-slugs-background.sql; no live database access.');
}
