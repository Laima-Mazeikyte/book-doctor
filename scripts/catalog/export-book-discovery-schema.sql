-- Run this whole file in Supabase SQL Editor as postgres.
-- One read-only SELECT over PostgreSQL catalogs; never reads book/user rows.
-- Share the schema_sql result with backend. It contains only public.books
-- columns, constraints, indexes, SELECT policies and table/column grants.
-- Includes effective read access for anon/authenticated, accounting for inherited
-- grants and policy roles. No credentials, function bodies,
-- trigger arguments, application data or definitions from other tables.
-- This is a reference export, NOT a migration to run against the live database.
-- Referenced schemas/functions/tables are intentionally not exported.

with target as (
  select c.oid, c.relowner, c.relacl, c.relnamespace,
    c.relrowsecurity, c.relforcerowsecurity
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relname = 'books' and c.relkind in ('r', 'p')
), columns as (
  select a.attnum, pg_catalog.format('  %I %s%s%s%s',
    a.attname,
    pg_catalog.format_type(a.atttypid, a.atttypmod),
    case when a.attcollation <> 0 and a.attcollation <> t.typcollation
      then pg_catalog.format(' COLLATE %I.%I', cn.nspname, co.collname)
      else '' end,
    case
      when a.attidentity = 'a' then ' GENERATED ALWAYS AS IDENTITY'
      when a.attidentity = 'd' then ' GENERATED BY DEFAULT AS IDENTITY'
      when a.attgenerated = 's' then pg_catalog.format(
        ' GENERATED ALWAYS AS (%s) STORED', pg_catalog.pg_get_expr(d.adbin, d.adrelid))
      when a.attgenerated = 'v' then pg_catalog.format(
        ' GENERATED ALWAYS AS (%s) VIRTUAL', pg_catalog.pg_get_expr(d.adbin, d.adrelid))
      when d.oid is not null then ' DEFAULT ' || pg_catalog.pg_get_expr(d.adbin, d.adrelid)
      else '' end,
    case when a.attnotnull then ' NOT NULL' else '' end
  ) as definition
  from target b
  join pg_catalog.pg_attribute a on a.attrelid = b.oid
  join pg_catalog.pg_type t on t.oid = a.atttypid
  left join pg_catalog.pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  left join pg_catalog.pg_collation co on co.oid = a.attcollation
  left join pg_catalog.pg_namespace cn on cn.oid = co.collnamespace
  where a.attnum > 0 and not a.attisdropped
), constraints as (
  select c.conname, pg_catalog.format(
    'ALTER TABLE public.books ADD CONSTRAINT %I %s;',
    c.conname, pg_catalog.pg_get_constraintdef(c.oid, false)
  ) as definition
  from target b
  join pg_catalog.pg_constraint c on c.conrelid = b.oid
  -- NOT NULL is already represented in the column definition.
  where c.contype in ('p', 'u', 'f', 'c', 'x')
), indexes as (
  select ic.relname, pg_catalog.format(
    E'-- Index valid=%s, ready=%s\n%s;',
    i.indisvalid, i.indisready, pg_catalog.pg_get_indexdef(i.indexrelid)
  ) as definition
  from target b
  join pg_catalog.pg_index i on i.indrelid = b.oid
  join pg_catalog.pg_class ic on ic.oid = i.indexrelid
  -- Constraint-backed indexes are created by the constraints above.
  where not exists (
    select 1 from pg_catalog.pg_constraint c
    where c.conrelid = b.oid and c.conindid = i.indexrelid and c.contype in ('p', 'u', 'x')
  )
), readers as (
  select r.oid, r.rolname, r.rolsuper, r.rolbypassrls
  from pg_catalog.pg_roles r
  where r.rolname in ('anon', 'authenticated')
), select_policies as (
  select p.polname, pg_catalog.format(
    E'-- Applies to API roles (including inheritance): %s\n'
    'CREATE POLICY %I ON public.books AS %s FOR %s TO %s%s%s;',
    (select coalesce(pg_catalog.jsonb_object_agg(r.rolname, exists (
      select 1 from pg_catalog.unnest(p.polroles) as policy_roles(role_id)
      where case when role_id = 0 then true
        else pg_catalog.pg_has_role(r.oid, role_id, 'USAGE') end
    )), '{}'::jsonb) from readers r),
    p.polname,
    case when p.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end,
    case when p.polcmd = '*' then 'ALL' else 'SELECT' end,
    (select pg_catalog.string_agg(
      case when role_id = 0 then 'PUBLIC'
        else pg_catalog.quote_ident(pg_catalog.pg_get_userbyid(role_id)) end,
      ', ' order by role_id
    ) from pg_catalog.unnest(p.polroles) as policy_roles(role_id)),
    case when p.polqual is not null then pg_catalog.format(
      ' USING (%s)', pg_catalog.pg_get_expr(p.polqual, p.polrelid)) else '' end,
    case when p.polwithcheck is not null then pg_catalog.format(
      ' WITH CHECK (%s)', pg_catalog.pg_get_expr(p.polwithcheck, p.polrelid)) else '' end
  ) as definition
  from target b
  join pg_catalog.pg_policy p on p.polrelid = b.oid
  -- ALL policies also govern SELECT; write-only policies do not.
  where p.polcmd in ('r', '*')
), table_grants as (
  select x.grantee, x.privilege_type, x.grantor, pg_catalog.format(
    E'-- Grantor: %I\nGRANT %s ON TABLE public.books TO %s%s;',
    pg_catalog.pg_get_userbyid(x.grantor), x.privilege_type,
    case when x.grantee = 0 then 'PUBLIC'
      else pg_catalog.quote_ident(pg_catalog.pg_get_userbyid(x.grantee)) end,
    case when x.is_grantable then ' WITH GRANT OPTION' else '' end
  ) as definition
  from target b
  cross join lateral pg_catalog.aclexplode(
    coalesce(b.relacl, pg_catalog.acldefault('r', b.relowner))
  ) x
), column_read_grants as (
  select a.attnum, x.grantee, x.grantor, pg_catalog.format(
    E'-- Grantor: %I\nGRANT SELECT (%I) ON TABLE public.books TO %s%s;',
    pg_catalog.pg_get_userbyid(x.grantor), a.attname,
    case when x.grantee = 0 then 'PUBLIC'
      else pg_catalog.quote_ident(pg_catalog.pg_get_userbyid(x.grantee)) end,
    case when x.is_grantable then ' WITH GRANT OPTION' else '' end
  ) as definition
  from target b
  join pg_catalog.pg_attribute a on a.attrelid = b.oid
  cross join lateral pg_catalog.aclexplode(a.attacl) x
  where a.attnum > 0 and not a.attisdropped and x.privilege_type = 'SELECT'
), reader_access as (
  select r.rolname, pg_catalog.jsonb_build_object(
    'role', r.rolname,
    'schema_usage', pg_catalog.has_schema_privilege(r.oid, b.relnamespace, 'USAGE'),
    'table_select', pg_catalog.has_table_privilege(r.oid, b.oid, 'SELECT'),
    'readable_columns', (select coalesce(pg_catalog.jsonb_agg(a.attname order by a.attnum), '[]'::jsonb)
      from pg_catalog.pg_attribute a
      where a.attrelid = b.oid and a.attnum > 0 and not a.attisdropped
        and pg_catalog.has_column_privilege(r.oid, b.oid, a.attnum, 'SELECT')),
    'superuser', r.rolsuper,
    'bypass_rls', r.rolbypassrls,
    'inherits_table_owner', pg_catalog.pg_has_role(r.oid, b.relowner, 'USAGE')
  ) as details
  from target b cross join readers r
)
select pg_catalog.format(
  E'-- public.books reference export, captured %s\n'
  '-- Schema/index metadata only; not a complete restore script.\n'
  '-- book_id: public text ULID; id: separate catalog UUID.\n'
  '-- API title maps to book_name; public URL is /books/<stored slug>.\n'
  '-- Current frontend availability: an existing row returned by catalog RLS.\n'
  '-- The book-detail query has no soft-delete/status predicate.\n'
  '-- Missing row -> 404; catalog read failure -> 503.\n'
  '-- This export does not infer availability from NULL characteristics or absent vectors.\n'
  '-- Owner=%I; RLS enabled=%s, forced=%s.\n'
  '-- ALL policies are included because they also apply to SELECT.\n'
  '-- Effective reader privileges include inherited/PUBLIC grants, not row visibility.\n'
  '-- Policy expressions may depend on JWT/session values; inspect before claiming equal visibility.\n'
  '-- Referenced policy functions are not exported.\n\n'
  'CREATE TABLE public.books (\n%s\n);\n\n%s\n\n%s\n\n'
  'ALTER TABLE public.books %s ROW LEVEL SECURITY;\n'
  'ALTER TABLE public.books %s ROW LEVEL SECURITY;\n\n'
  '-- SELECT / ALL policies\n%s\n\n-- Table grants (all privileges)\n%s\n\n'
  '-- Column-level SELECT grants\n%s\n\n-- Effective API reader access\n-- %s\n',
  pg_catalog.statement_timestamp(), pg_catalog.pg_get_userbyid(b.relowner),
  b.relrowsecurity, b.relforcerowsecurity,
  (select pg_catalog.string_agg(definition, E',\n' order by attnum) from columns),
  coalesce((select pg_catalog.string_agg(definition, E'\n' order by conname) from constraints), ''),
  coalesce((select pg_catalog.string_agg(definition, E'\n' order by relname) from indexes), ''),
  case when b.relrowsecurity then 'ENABLE' else 'DISABLE' end,
  case when b.relforcerowsecurity then 'FORCE' else 'NO FORCE' end,
  coalesce((select pg_catalog.string_agg(definition, E'\n' order by polname) from select_policies), '-- None'),
  coalesce((select pg_catalog.string_agg(definition, E'\n' order by grantee, privilege_type, grantor) from table_grants), '-- None'),
  coalesce((select pg_catalog.string_agg(definition, E'\n' order by attnum, grantee, grantor) from column_read_grants), '-- None'),
  coalesce((select pg_catalog.jsonb_agg(details order by rolname) from reader_access), '[]'::jsonb)
) as schema_sql
from target b;
